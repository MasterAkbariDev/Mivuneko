import { readFileSync, writeFileSync, existsSync } from "node:fs";
const { jobs } = JSON.parse(
  readFileSync("assets/characters/illustrated-art-jobs.json", "utf8"),
);
const records = {};
for (const job of jobs) {
  const filename = `${job.id}-${job.type === "emotion" ? "emotions-" : ""}${job.part}-hq.png`;
  const file = `apps/desktop/public/characters/${filename}`;
  if (!existsSync(file)) continue;
  const bytes = readFileSync(file),
    w = bytes.readUInt32BE(16),
    h = bytes.readUInt32BE(20);
  if (w / 3 < 480 || h / 2 < 480)
    throw Error(`${filename} has insufficient source detail: ${w}x${h}`);
  const record = (records[job.id] ??= { poses: [], motion: [] });
  if (job.type === "emotion")
    record.poses.push({ file: `/characters/${filename}`, names: job.names });
  else record.motion[Number(job.part.slice(-1))] = `/characters/${filename}`;
}
writeFileSync(
  "apps/desktop/src/highResolutionCharacters.ts",
  "// Generated by scripts/collect-character-art.mjs.\nexport const detailedArtwork: Record<string,{poses:{file:string;names:string[]}[];motion:(string|null)[]}> = " +
    JSON.stringify(records, null, 2) +
    ";\n",
);
console.log(
  `Registered ${Object.values(records).reduce((n, r) => n + r.poses.length + r.motion.filter(Boolean).length, 0)} high-resolution sheets.`,
);
